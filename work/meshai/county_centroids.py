def same_to_county_fips(same) -> Optional[str]:
    """Normalise a CAP SAME geocode (PSSCCC) to a 5-digit county FIPS (SSCCC).

    The leading part-of-county digit P is stripped; the trailing 5 digits are
    the county FIPS. Returns None for anything that is not a 5-or-6-digit
    numeric SAME token. A leading part digit other than 0 (a partial-county
    alert) still resolves to the whole county — the centroid is the best
    available point for a sub-county area.
    """
    if same is None:
        return None
    s = str(same).strip()
    if not s.isdigit():
        return None
    if len(s) == 6:
        s = s[1:]  # strip the leading part-of-county digit
    if len(s) != 5:
        return None
    return s


def centroid_for_county_fips(fips) -> Optional[tuple[float, float]]:
    """Return the (lat, lon) internal point for a 5-digit county FIPS, or None."""
    if fips is None:
        return None
    return COUNTY_CENTROIDS.get(str(fips).strip())


def centroid_for_same(same) -> Optional[tuple[float, float]]:
    """Resolve a CAP SAME geocode straight to a (lat, lon) internal point, or None."""
    return centroid_for_county_fips(same_to_county_fips(same))
